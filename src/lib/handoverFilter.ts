import type { KnowledgeFinding, ProjectData, ConflictRecord } from './types.ts';

/**
 * Filter findings for the final handover dossier.
 * RULE 1: Only approved and non-rejected findings may appear.
 * RULE 2: Rejected findings must never appear.
 * RULE 3: Unapproved findings must never appear.
 */
export function getApprovedFindings(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return findings.filter((f) => f.approved === true && !f.rejected);
}

export function getHandoverDecisions(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return getApprovedFindings(findings).filter((f) => f.type === 'decision');
}

export function getHandoverTasks(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return getApprovedFindings(findings).filter((f) => f.type === 'task');
}

export function getHandoverRisks(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return getApprovedFindings(findings).filter((f) => f.type === 'risk');
}

export function getHandoverDependencies(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return getApprovedFindings(findings).filter((f) => f.type === 'dependency');
}

export function getHandoverNextActions(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return getApprovedFindings(findings).filter((f) => f.type === 'next_action');
}

export function getHandoverQuestions(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return getApprovedFindings(findings).filter((f) => f.type === 'unresolved_question');
}

export function getHandoverContacts(findings: KnowledgeFinding[]): KnowledgeFinding[] {
  return getApprovedFindings(findings).filter((f) => f.type === 'contact');
}

export interface HandoverBlockStatus {
  isBlocked: boolean;
  canCertify: boolean;
  unresolvedConflictsCount: number;
  unreviewedCount: number;
  totalFindingsCount: number;
  approvedCount: number;
  rejectedCount: number;
  reason: string;
}

/**
 * Evaluates whether handover generation and viewing should be blocked.
 * Handover generation is blocked until:
 * 1. All critical conflicts are resolved (0 conflicting findings).
 * 2. All required findings are reviewed (0 unreviewed findings).
 */
export function checkHandoverBlockStatus(
  findings: KnowledgeFinding[],
  handoverCertified: boolean,
  conflicts?: ConflictRecord[]
): HandoverBlockStatus {
  const totalFindingsCount = findings.length;
  const openConflictsCount = (conflicts || []).filter((c) => c.status === 'OPEN').length;
  const conflictingFindingsCount = findings.filter((f) => f.status === 'CONFLICTING').length;
  const unresolvedConflictsCount = Math.max(openConflictsCount, conflictingFindingsCount);
  const unreviewedCount = findings.filter((f) => !f.approved && !f.rejected).length;
  const approvedCount = findings.filter((f) => f.approved && !f.rejected).length;
  const rejectedCount = findings.filter((f) => f.rejected).length;

  const canCertify = unresolvedConflictsCount === 0 && unreviewedCount === 0;

  // Handover is blocked if not yet certified AND (has conflicts OR has unreviewed items)
  let isBlocked = false;
  let reason = '';

  if (unresolvedConflictsCount > 0) {
    isBlocked = true;
    reason = `${unresolvedConflictsCount} unresolved conflict(s) must be resolved in Review Center.`;
  } else if (unreviewedCount > 0) {
    isBlocked = true;
    reason = `${unreviewedCount} finding(s) require human review before handover can be generated.`;
  } else if (!handoverCertified) {
    // If all are reviewed and 0 conflicts, but not yet formally certified with signature
    isBlocked = true;
    reason = 'All findings reviewed. Final certification signature required in Review Center.';
  }

  return {
    isBlocked,
    canCertify,
    unresolvedConflictsCount,
    unreviewedCount,
    totalFindingsCount,
    approvedCount,
    rejectedCount,
    reason,
  };
}

/**
 * Generates clean, tamper-evident Markdown export containing ONLY approved findings.
 */
export function generateHandoverMarkdown(project: ProjectData): string {
  const approvedDecisions = getHandoverDecisions(project.findings);
  const approvedTasks = getHandoverTasks(project.findings);
  const approvedRisks = getHandoverRisks(project.findings);
  const approvedDependencies = getHandoverDependencies(project.findings);
  const approvedNextActions = getHandoverNextActions(project.findings);
  const approvedQuestions = getHandoverQuestions(project.findings);

  return `# ${project.name} — Handover Dossier
**Generated by KnoTrail Platform** (Deploy_or_Die)
**Audit Trail:** #${project.code}-CERT-9921
**Status:** ${project.handoverCertified ? 'Certified & Signed Off' : 'Draft / Uncertified'}
**Certification Hash:** ${project.handoverCertified ? project.certificationHash : 'PENDING_FINAL_SIGN_OFF'}
**Date:** ${project.certifiedDate || 'Draft'}
**Signer:** ${project.certifiedBy || 'Pending Human Review Sign-Off'}

---

## Executive Summary
${project.executiveSummary}

---

## 1. Verified Architectural Decisions (${approvedDecisions.length})
${
  approvedDecisions.length > 0
    ? approvedDecisions
        .map(
          (f, i) => `### ${i + 1}. ${f.title}
- **Status:** ${f.status} (${f.confidence}% confidence)
- **Summary:** ${f.summary}
- **Reasoning:** ${f.reasoning || 'N/A'}
- **Impact:** ${f.impact || 'N/A'}
- **Owner:** ${f.owner}
- **Citations:** ${f.citations.map((c) => `${c.file}:${c.lineRange} (${c.commitSha || 'ref'})`).join(', ')}
`
        )
        .join('\n')
    : '_No approved decisions included._\n'
}

---

## 2. Operational Tasks & Responsibilities (${approvedTasks.length})
${
  approvedTasks.length > 0
    ? approvedTasks
        .map(
          (f, i) => `### ${i + 1}. [${f.urgency.toUpperCase()}] ${f.title}
- **Status:** ${f.status}
- **Owner:** ${f.owner}
- **Details:** ${f.summary}
`
        )
        .join('\n')
    : '_No approved tasks included._\n'
}

---

## 3. Risk Register & Mitigations (${approvedRisks.length})
${
  approvedRisks.length > 0
    ? approvedRisks
        .map(
          (f, i) => `### ${i + 1}. ${f.title}
- **Urgency:** ${f.urgency.toUpperCase()}
- **Risk Assessment:** ${f.summary}
- **Mitigation Status:** ${f.reviewerNotes || 'Pending SRE validation'}
`
        )
        .join('\n')
    : '_No approved risks included._\n'
}

---

## 4. Technical Dependencies & Integrations (${approvedDependencies.length})
${
  approvedDependencies.length > 0
    ? approvedDependencies
        .map(
          (f, i) => `### ${i + 1}. ${f.title}
- **Status:** ${f.status} (${f.confidence}% confidence)
- **Category:** ${f.category}
- **Details:** ${f.summary}
- **Owner:** ${f.owner}
- **Citations:** ${f.citations.map((c) => `${c.file}:${c.lineRange}`).join(', ')}
`
        )
        .join('\n')
    : '_No approved dependencies included._\n'
}

---

## 5. Key Transition Contacts
${project.stakeholders
  .map((s) => `- **${s.name}** (${s.role}): ${s.email} — ${s.transitionNotes}`)
  .join('\n')}

---
*Certified Tamper-Proof Document sealed by KnoTrail Handover Engine.*
`;
}

/**
 * Generates structured JSON export containing ONLY approved findings.
 */
export function generateHandoverJSON(project: ProjectData): Record<string, unknown> {
  const approvedFindings = getApprovedFindings(project.findings);
  const approvedDecisions = getHandoverDecisions(project.findings);
  const approvedTasks = getHandoverTasks(project.findings);
  const approvedRisks = getHandoverRisks(project.findings);
  const approvedDependencies = getHandoverDependencies(project.findings);
  const approvedNextActions = getHandoverNextActions(project.findings);
  const approvedQuestions = getHandoverQuestions(project.findings);

  return {
    project: project.name,
    code: project.code,
    version: project.version,
    auditStamp: `#${project.code}-CERT-9921`,
    handoverCertified: project.handoverCertified,
    certificationHash: project.handoverCertified ? project.certificationHash : null,
    certifiedBy: project.certifiedBy || null,
    certifiedDate: project.certifiedDate || null,
    executiveSummary: project.executiveSummary,
    stakeholders: project.stakeholders,
    statistics: {
      totalApprovedFindings: approvedFindings.length,
      approvedDecisionsCount: approvedDecisions.length,
      approvedTasksCount: approvedTasks.length,
      approvedRisksCount: approvedRisks.length,
      approvedDependenciesCount: approvedDependencies.length,
    },
    findings: approvedFindings,
    decisions: approvedDecisions,
    tasks: approvedTasks,
    risks: approvedRisks,
    dependencies: approvedDependencies,
    nextActions: approvedNextActions,
    questions: approvedQuestions,
  };
}
